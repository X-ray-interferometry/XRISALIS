LEGACY_HEX = ["#000000", "#242037", "#344871", "#89A4E3", "#E2F6FE"]

XRI_HEX = tuple("#%02x%02x%02x" % tuple(np.round(c * 255).astype(int))
                for c in XRI_RGB)

xri_cmap = LinearSegmentedColormap.from_list("xri", list(map(tuple, XRI_RGB)),
                                             N=1024)
xri_cmap_r = xri_cmap.reversed(name="xri_r")
xri_legacy = LinearSegmentedColormap.from_list("xri_legacy", LEGACY_HEX,
                                               N=1024)


def _register():
    try:                                  # Matplotlib >= 3.5
        import matplotlib as mpl
        for cm in (xri_cmap, xri_cmap_r, xri_legacy):
            if cm.name not in mpl.colormaps:
                mpl.colormaps.register(cm)
    except Exception:                     # pragma: no cover - cosmetic only
        pass


_register()


def lut(n=256):
    """The colormap as an ``(n, 3)`` float array in [0, 1]."""
    if n == len(XRI_RGB):
        return XRI_RGB.copy()
    return xri_cmap(np.linspace(0.0, 1.0, n))[:, :3]
